#Arithmetic Operator 
morning_steps = 4800
afternoon_steps = 3200

#addition
total_steps = morning_steps + afternoon_steps
print(f"Total steps today: {total_steps}")

#subtraction
steps_remaining = 10000 - total_steps
print(f"Steps remaining to reach target: {steps_remaining}")

#multiplication
weekly_target_steps = 10000 * 7
print(f"Weekly target steps: {weekly_target_steps}")

#division
daily_average_steps = 67000 / 7
print(f"Daily average steps this week: {daily_average_steps}")